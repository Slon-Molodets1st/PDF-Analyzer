"""Цепь для извлечения структурированной информации из контрактов"""

from langchain_core.prompts import ChatPromptTemplate
from src.models.contract_schema import ContractSchema

EXTRACTION_TEMPLATE = """
Ты - эксперт по анализу юридических и финансовых документов.
Извлеки структурированную информацию из предоставленного текста контракта.

ВАЖНО: Возвращай ответ строго в формате JSON, соответствующий схеме ContractSchema.

Примеры извлечения:

Пример 1:
Текст: "ООО 'ТехноСервис' (Заказчик) и ООО 'Поставщик' заключили договор поставки оборудования на сумму 5 200 000 (Пять миллионов двести тысяч) рублей. Договор подписан 15 марта 2024 года. Риски: несвоевременная поставка может привести к штрафным санкциям, недостаточное качество оборудования может стать причиной судебных разбирательств, отсутствие гарантийного обслуживания увеличивает эксплуатационные расходы."

Ответ: {{
    "company_name": "ООО 'ТехноСервис'",
    "total_amount": 5200000,
    "signing_date": "15.03.2024",
    "risks": [
        "Несвоевременная поставка оборудования приведет к штрафным санкциям",
        "Недостаточное качество оборудования может стать причиной судебных разбирательств",
        "Отсутствие гарантийного обслуживания увеличивает эксплуатационные расходы"
    ],
    "additional_terms": ["Договор поставки оборудования"]
}}

Пример 2:
Текст: "ЗАО 'СтройИнвест' выступает заказчиком строительства торгового центра. Стоимость работ составляет 15 750 000 рублей. Договор подписан 28.11.2023. Основные риски: задержки финансирования со стороны заказчика могут остановить строительство, погодные условия могут повлиять на сроки сдачи объекта, изменения в законодательстве могут потребовать дополнительных согласований."

Ответ: {{
    "company_name": "ЗАО 'СтройИнвест'",
    "total_amount": 15750000,
    "signing_date": "28.11.2023",
    "risks": [
        "Задержки финансирования со стороны заказчика могут остановить строительство",
        "Погодные условия могут повлиять на сроки сдачи объекта",
        "Изменения в законодательстве могут потребовать дополнительных согласований"
    ],
    "additional_terms": ["Строительство торгового центра"]
}}

Теперь проанализируй следующий текст:

{text}

{format_instructions}
"""

def create_extraction_chain(llm):
    """
    Создает цепь для извлечения структурированной информации
    
    Args:
        llm: объект LLM
    
    Returns:
        chain: готовая к использованию цепь
    """
    # Используем structured output
    structured_llm = llm.with_structured_output(ContractSchema)
    
    extraction_prompt = ChatPromptTemplate.from_template(EXTRACTION_TEMPLATE)
    
    chain = extraction_prompt | structured_llm
    
    return chain
